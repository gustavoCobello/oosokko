function toastySprite(){
  if(SPR_CACHE['toasty-spam-evil'])return SPR_CACHE['toasty-spam-evil'];
  const w=TOASTY_ROWS[0].length,h=TOASTY_ROWS.length,c=document.createElement('canvas');c.width=w;c.height=h;
  const g=c.getContext('2d'),im=g.createImageData(w,h);
  for(let y=0;y<h;y++)for(let x=0;x<w;x++){const ch=TOASTY_ROWS[y][x];if(ch==='.')continue;const n=parseInt(TOASTY_PAL[ch].slice(1),16),i=(y*w+x)*4;im.data[i]=n>>16&255;im.data[i+1]=n>>8&255;im.data[i+2]=n&255;im.data[i+3]=255}
  g.putImageData(im,0,0);return SPR_CACHE['toasty-spam-evil']=c;
}
